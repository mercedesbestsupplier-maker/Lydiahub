function renderSkills() {
  els.skills.innerHTML = DATA.skills.map((skill) => {
    const gh = githubUrl(skill);
    const githubClass = gh ? (DATA.repoExists ? "" : "pending") : "disabled";
    const githubLabel = DATA.repoExists ? "GitHub" : "私信获取";
    const downloadButton = skill.hasPackage
      ? `<a class="card-action" href="${assetHref(skill.download)}" download>${skill.downloadLabel || "下载 zip"}</a>`
      : `<span class="github-link disabled">待制作</span>`;
    return `
      <article class="skill-card">
        <div class="card-top">
          <span class="badge">${skill.category}</span>
          <span class="stars">${skill.starsText}</span>
        </div>
        <div>
          <h3 class="card-title">${skill.title}</h3>
          <div class="slug">${skill.slug}</div>
        </div>
        <p class="signal">${skill.signal}</p>
        <div class="card-meta">
          <span class="pill">${skill.business}</span>
          <span class="pill">${skill.platform}</span>
          <span class="pill">${skill.priority}</span>
          <span class="pill">${skill.status}</span>
        </div>
        <div class="card-actions">
          ${downloadButton}
          <a class="github-link ${githubClass}" href="${gh || "#"}">${githubLabel}</a>
        </div>
      </article>
    `;
  }).join("");
}

