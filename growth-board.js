function pageParams() {
  return new URLSearchParams(window.location.search);
}

function currentContext() {
  const params = pageParams();
  const desk = params.get("desk") || "";
  const flow = params.get("flow") || "";
  const slug = params.get("slug") || "";
  return {
    desk,
    flow,
    slug,
    detail: RESEARCH_CONTEXTS[desk] || null
  };
}

function marketMatch(item, desk) {
  if (!desk) return true;
  if (desk === "china-research") {
    return item.market_tags.includes("china") || item.market_tags.includes("universal");
  }
  if (desk === "overseas-research") {
    return item.market_tags.includes("overseas") || item.market_tags.includes("universal");
  }
  return true;
}

function flowMatch(item, flow) {
  if (!flow) return true;
  return item.flow_tags.includes(flow);
}

function contextScore(item, desk, flow) {
  let score = item.score || 0;
  if (desk === "china-research") {
    if (item.market_tags.includes("china")) score += 20;
    else if (item.market_tags.includes("universal")) score += 8;
    else score -= 20;
  }
  if (desk === "overseas-research") {
    if (item.market_tags.includes("overseas")) score += 20;
    else if (item.market_tags.includes("universal")) score += 8;
    else score -= 20;
  }
  if (flow) {
    if (item.flow_tags.includes(flow)) score += 12;
    else score -= 6;
  }
  return score;
}

function rankedItems() {
  const { desk, flow, slug } = currentContext();
  const marketMatched = OPS_DATA.items.filter((item) => marketMatch(item, desk));
  const narrowed = flow ? marketMatched.filter((item) => flowMatch(item, flow)) : marketMatched;
  const source = narrowed.length ? narrowed : marketMatched;
  return [...source].sort((a, b) => {
    if (slug) {
      if (a.slug === slug && b.slug !== slug) return -1;
      if (b.slug === slug && a.slug !== slug) return 1;
    }
    const scoreDiff = contextScore(b, desk, flow) - contextScore(a, desk, flow);
    if (scoreDiff) return scoreDiff;
    return (b.score || 0) - (a.score || 0);
  });
}

function contextHref(base, extra = {}, hash = "") {
  const { desk, flow, slug } = currentContext();
  const url = new URL(base, window.location.href);
  if (desk) url.searchParams.set("desk", desk);
  if (flow) url.searchParams.set("flow", flow);
  if (slug) url.searchParams.set("slug", slug);
  Object.entries(extra).forEach(([key, value]) => {
    if (value === undefined || value === null || value === "") return;
    url.searchParams.set(key, value);
  });
  if (hash) {
    url.hash = hash.startsWith("#") ? hash : `#${hash}`;
  }
  return `${url.pathname.split('/').pop()}${url.search}${url.hash}`;
}

function currentSelectedItem() {
  const ranked = rankedItems();
  const { slug } = currentContext();
  return ranked.find((item) => item.slug === slug) || ranked[0] || null;
}

function decisionMetrics(item) {
  const { desk, flow } = currentContext();
  if (!item) return null;
  const marketFit = desk
    ? (marketMatch(item, desk) ? (item.market_tags.includes("universal") ? 84 : 96) : 58)
    : (item.market_tags.includes("universal") ? 88 : 94);
  const flowFit = flow
    ? (flowMatch(item, flow) ? 95 : 68)
    : (item.flow_tags.includes("close") ? 93 : item.flow_tags.includes("content") ? 91 : 86);
  const channelReadiness = item.channel.includes("小红书") || item.channel.includes("抖音")
    ? 95
    : item.channel.includes("LinkedIn")
      ? 91
      : 87;
  const monetizationReady = item.flow_tags.includes("close")
    ? 96
    : item.flow_tags.includes("mvp")
      ? 89
      : 84;
  const priority = Math.min(
    99,
    Math.round(contextScore(item, desk, flow) * 0.45 + marketFit * 0.18 + flowFit * 0.15 + channelReadiness * 0.1 + monetizationReady * 0.12)
  );
  const label = priority >= 92 ? "今天开推" : priority >= 84 ? "本周重点" : priority >= 76 ? "加入备选" : "继续观察";
  const advice = label === "今天开推"
    ? "这条 Skill 已经具备内容入口、可下载包和后续承接空间，适合今天直接作为主推对象。"
    : label === "本周重点"
      ? "这条 Skill 适合排进本周节奏，先拿内容和私信数据确认转化强度。"
      : label === "加入备选"
        ? "先把它放进候选位，等当前主推项跑完再接力测试。"
        : "先继续积累需求证据，不要急着消耗主阵地流量。";
  const warning = !item.download
    ? "这条 Skill 还没有下载包，先别重推，至少要把安装资源和说明补齐。"
    : flow === "close"
      ? "当前入口更偏成交承接，别只发内容，要同步准备问诊和报价边界。"
      : flow === "mvp"
        ? "当前入口更偏试卖验证，别只讲方法论，记得带报名、waitlist 或留资动作。"
        : "当前入口更偏内容放量，先确保标题、封面和评论关键词都足够直接。";
  return { marketFit, flowFit, channelReadiness, monetizationReady, priority, label, advice, warning };
}

