function pageParams() {
  return new URLSearchParams(window.location.search);
}

function currentContext() {
  const params = pageParams();
  const desk = params.get("desk") || "";
  const flow = params.get("flow") || "";
  const slug = params.get("slug") || "";
  return {
    desk,
    flow,
    slug,
    detail: RESEARCH_CONTEXTS[desk] || null
  };
}

function isMarketMatch(kit, desk) {
  if (!desk) return true;
  if (desk === "china-research") {
    return kit.marketTags.includes("china") || kit.marketTags.includes("universal");
  }
  if (desk === "overseas-research") {
    return kit.marketTags.includes("overseas") || kit.marketTags.includes("universal");
  }
  return true;
}

function isFlowMatch(kit, flow) {
  if (!flow) return true;
  return kit.flowTags.includes(flow);
}

function contextScore(kit, desk, flow) {
  let score = kit.score || 0;
  if (desk === "china-research") {
    if (kit.marketTags.includes("china")) score += 20;
    else if (kit.marketTags.includes("universal")) score += 8;
    else score -= 20;
  }
  if (desk === "overseas-research") {
    if (kit.marketTags.includes("overseas")) score += 20;
    else if (kit.marketTags.includes("universal")) score += 8;
    else score -= 20;
  }
  if (flow) {
    if (kit.flowTags.includes(flow)) score += 15;
    else score -= 6;
  }
  return score;
}

function sortedKits() {
  const { desk, flow, slug } = currentContext();
  const marketMatched = LAUNCH_KITS.filter((kit) => isMarketMatch(kit, desk));
  const narrowed = flow ? marketMatched.filter((kit) => isFlowMatch(kit, flow)) : marketMatched;
  const source = narrowed.length ? narrowed : marketMatched;
  return [...source]
    .sort((a, b) => {
      if (slug) {
        if (a.slug === slug && b.slug !== slug) return -1;
        if (b.slug === slug && a.slug !== slug) return 1;
      }
      const scoreDiff = contextScore(b, desk, flow) - contextScore(a, desk, flow);
      if (scoreDiff) return scoreDiff;
      return a.rank - b.rank;
    });
}

function contextHref(base, extra = {}, hash = "") {
  const { desk, flow, slug } = currentContext();
  const url = new URL(base, window.location.href);
  if (desk) url.searchParams.set("desk", desk);
  if (flow) url.searchParams.set("flow", flow);
  if (slug) url.searchParams.set("slug", slug);
  Object.entries(extra).forEach(([key, value]) => {
    if (value === undefined || value === null || value === "") return;
    url.searchParams.set(key, value);
  });
  if (hash) {
    url.hash = hash.startsWith("#") ? hash : `#${hash}`;
  }
  return `${url.pathname.split('/').pop()}${url.search}${url.hash}`;
}

function kitDecision(kit) {
  const { desk, flow } = currentContext();
  const marketFit = desk
    ? (isMarketMatch(kit, desk) ? (kit.marketTags.includes("universal") ? 84 : 96) : 58)
    : (kit.marketTags.includes("universal") ? 88 : 94);
  const flowFit = flow
    ? (isFlowMatch(kit, flow) ? 96 : 66)
    : (kit.flowTags.includes("content") ? 92 : 84);
  const publishEase = ["内容增长", "短视频转化", "视觉转化"].includes(kit.business)
    ? 95
    : ["海外增长", "办公提效", "私域成交"].includes(kit.business)
      ? 88
      : 80;
  const conversionReady = kit.flowTags.includes("close")
    ? 94
    : kit.flowTags.includes("mvp")
      ? 86
      : 82;
  const priority = Math.min(
    99,
    Math.round(contextScore(kit, desk, flow) * 0.45 + marketFit * 0.2 + flowFit * 0.18 + publishEase * 0.1 + conversionReady * 0.07)
  );
  const label = priority >= 92 ? "今天就发" : priority >= 84 ? "本周主推" : priority >= 76 ? "加入备选" : "继续观察";
  const advice = label === "今天就发"
    ? "这套素材现在就值得发，适合直接拿去挂免费 Skill 做流量入口。"
    : label === "本周主推"
      ? "这套素材适合排进本周计划，优先验证评论、私信和领取动作。"
      : label === "加入备选"
        ? "先保留在候选区，等对应市场或分支的主推项发完再上。"
        : "这套素材暂时不抢前排，先观察同类内容的反馈。";
  const warning = flow === "close"
    ? "这一批更偏承接和成交，不要只发内容，要同步准备私信问诊和报价边界。"
    : flow === "mvp"
      ? "这一批更偏试卖验证，别只发方法论，记得带报名、私信或 waitlist 动作。"
      : "这一批更偏内容曝光，先保证标题、封面和评论关键词足够清晰。";
  return { marketFit, flowFit, publishEase, conversionReady, priority, label, advice, warning };
}

