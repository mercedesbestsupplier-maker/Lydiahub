function bindEvents() {
  el("actionFilter").addEventListener("change", (event) => {
    state.action = event.target.value;
    syncStateToUrl();
    renderBacklogDetail();
  });
  el("marketFilter").addEventListener("change", (event) => {
    state.market = event.target.value;
    syncStateToUrl();
    renderBacklogDetail();
  });
  el("teammateFilter").addEventListener("change", (event) => {
    state.teammate = event.target.value;
    syncStateToUrl();
    renderBacklogDetail();
  });
  el("skillFilter").addEventListener("change", (event) => {
    state.skill = event.target.value;
    syncStateToUrl();
    renderBacklogDetail();
  });
}

function init() {
  const params = pageParams();
  state.action = params.get("action") || "all";
  state.market = params.get("market") || "all";
  state.teammate = params.get("teammate") || "all";
  state.skill = params.get("skill") || "all";
  renderFilters();
  renderSummary();
  renderCandidates();
  renderOwners();
  renderEnhancementGroups();
  bindEvents();
  renderBacklogDetail();
}

