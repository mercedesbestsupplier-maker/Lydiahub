function syncStateToUrl() {
  const url = new URL(window.location.href);
  if (state.action !== "all") url.searchParams.set("action", state.action);
  else url.searchParams.delete("action");
  if (state.market !== "all") url.searchParams.set("market", state.market);
  else url.searchParams.delete("market");
  if (state.teammate !== "all") url.searchParams.set("teammate", state.teammate);
  else url.searchParams.delete("teammate");
  if (state.skill !== "all") url.searchParams.set("skill", state.skill);
  else url.searchParams.delete("skill");
  window.history.replaceState({}, "", `${url.pathname.split('/').pop()}${url.search}${url.hash}`);
}

function actionLabel(key) {
  return ACTION_LABELS[key] || key || "待判断";
}

function groupSlug(item) {
  return item.existingSkillSlug || (item.proposedSkill || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "untitled";
}

function filteredBacklog() {
  return RADAR_DATA.backlog.filter((item) => {
    return (state.action === "all" || item.actionGroup === state.action)
      && (state.market === "all" || (item.marketScope || "全球通用") === state.market)
      && (state.teammate === "all" || item.teammateId === state.teammate)
      && (state.skill === "all" || groupSlug(item) === state.skill);
  });
}

